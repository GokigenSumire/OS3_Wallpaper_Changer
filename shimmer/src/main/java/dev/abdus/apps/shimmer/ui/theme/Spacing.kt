package dev.abdus.apps.shimmer.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 设计系统间距规范
 * 基于 8dp 栅格系统
 */
object Spacing {
    val xs: Dp = 4.dp      // 紧密元素间距
    val s: Dp = 8.dp       // 标准内边距
    val m: Dp = 16.dp      // 卡片内边距、列表项间距
    val l: Dp = 24.dp      // 分区间距
    val xl: Dp = 32.dp     // 页面边距
    val xxl: Dp = 48.dp    // 大区块间距
}
